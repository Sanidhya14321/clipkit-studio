#!/usr/bin/env python3
"""Split docs/MASTER_PROMPT.md into docs/spec/NN-slug.md, one file per top-level section.

Re-run only when MASTER_PROMPT.md changes. docs/spec/INDEX.md is hand-written and never touched.
"""
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parent.parent
src = root / "docs" / "MASTER_PROMPT.md"
out = root / "docs" / "spec"
out.mkdir(parents=True, exist_ok=True)

# Short, stable file names per section number; unknown sections fall back to a title slug.
SLUGS = {
    0: "how-to-use", 1: "mission", 2: "architecture", 3: "layout-and-model", 4: "pipeline",
    5: "studio", 6: "agent-integration", 7: "assets", 8: "features", 9: "token-efficiency",
    10: "testing", 11: "claude-code-setup", 12: "phases", 13: "kickoff",
}

heading = re.compile(r"^## (\d+)\. (.+)$")
sections: list[tuple[int, str, list[str]]] = []
in_fence = False
for line in src.read_text(encoding="utf-8").splitlines():
    if line.startswith("```"):
        in_fence = not in_fence
    m = None if in_fence else heading.match(line)
    if m:
        sections.append((int(m.group(1)), m.group(2), [line]))
    elif sections:
        sections[-1][2].append(line)

if not sections:
    sys.exit("no '## N. Title' headings found")

for num, title, lines in sections:
    words = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-").split("-")
    slug = SLUGS.get(num, "-".join(words[:4]))
    path = out / f"{num:02d}-{slug}.md"
    note = "<!-- Generated by scripts/split-spec.py from docs/MASTER_PROMPT.md. Do not edit. -->\n\n"
    path.write_text(note + "\n".join(lines).rstrip() + "\n", encoding="utf-8")
    print(f"{path.relative_to(root)}  ({len(lines)} lines)")
