import { z } from 'zod';
import { zColor, zMultiline, zSlider } from '../../control';
import { defaultMotion, motionSchema, promoMeta } from '../../promo-common';
import type { ClipMeta } from '../../registry';

const unit = (max = 1, step = 0.01) => zSlider({ min: 0, max, step });

export const magnifierCaptionSchema = z.object({
  look: z.object({
    showBackdrop: z.boolean(),
    background: zColor(),
    spotlight: zColor(),
  }),
  caption: z.object({
    text: zMultiline(),
    font: z.enum(['serif', 'sans']),
    color: zColor(),
    size: zSlider({ min: 20, max: 110 }),
    weight: zSlider({ min: 300, max: 800, step: 100 }),
    lineHeight: zSlider({ min: 0.9, max: 1.8, step: 0.01 }),
    top: zSlider({ min: 0, max: 1600 }),
    charStagger: zSlider({ min: 0, max: 8, step: 0.1 }),
    wordFrames: zSlider({ min: 1, max: 60 }),
    charFade: zSlider({ min: 1, max: 20 }),
    underline: zSlider({ min: 0, max: 12, step: 0.5 }),
    underlineFrames: zSlider({ min: 1, max: 90 }),
  }),
  field: z.object({
    decoys: zMultiline(),
    shape: z.enum(['hexagon', 'circle']),
    seed: zSlider({ min: 1, max: 999 }),
    spread: zSlider({ min: 0.6, max: 4, step: 0.05 }),
    ring: zColor(),
    word: zColor(),
    lineWidth: zSlider({ min: 1, max: 12, step: 0.5 }),
    wordSize: zSlider({ min: 20, max: 80 }),
    wordWeight: zSlider({ min: 300, max: 800, step: 100 }),
    blur: zSlider({ min: 0, max: 20, step: 0.5 }),
    minRadius: zSlider({ min: 30, max: 200 }),
    maxRadius: zSlider({ min: 80, max: 320 }),
    targetRadius: zSlider({ min: 90, max: 300 }),
    gap: zSlider({ min: 0, max: 60 }),
    fill: unit(),
    fadeTop: zSlider({ min: 0, max: 1920 }),
    fadeBottom: zSlider({ min: 0, max: 1920 }),
    fadeLength: zSlider({ min: 1, max: 600 }),
    drift: zSlider({ min: 0, max: 4, step: 0.05 }),
  }),
  lens: z.object({
    x: zSlider({ min: 0, max: 1080 }),
    y: zSlider({ min: 0, max: 1920 }),
    radius: zSlider({ min: 120, max: 460 }),
    angle: zSlider({ min: -60, max: 60, step: 0.5 }),
    sway: unit(2),
    rim: zColor(),
    rimWidth: zSlider({ min: 1, max: 24, step: 0.5 }),
    handleLength: zSlider({ min: 0, max: 800 }),
    handleWidth: zSlider({ min: 16, max: 120 }),
    handleGap: zSlider({ min: 0, max: 60 }),
    handle: zColor(),
    glint: unit(),
    inside: zColor(),
    ring: zColor(),
    word: zColor(),
    lineWidth: zSlider({ min: 0.5, max: 8, step: 0.25 }),
    magnify: zSlider({ min: 1, max: 1.8, step: 0.01 }),
  }),
  glow: z.object({
    color: zColor(),
    accentWord: z.string(),
    accent: zColor(),
    accentText: zColor(),
    strength: unit(1.5),
    halo: zSlider({ min: 0, max: 40, step: 0.5 }),
    weight: zSlider({ min: 400, max: 800, step: 100 }),
  }),
  timing: z.object({
    firstWord: zSlider({ min: 0, max: 120 }),
    wordInterval: zSlider({ min: 12, max: 90, step: 0.05 }),
    travelFrames: zSlider({ min: 6, max: 80 }),
    firstMove: zSlider({ min: -30, max: 120 }),
    moveInterval: zSlider({ min: 12, max: 90, step: 0.05 }),
    returnFrame: zSlider({ min: 60, max: 600 }),
    returnFrames: zSlider({ min: 6, max: 120 }),
    fadeOutFrame: zSlider({ min: 60, max: 600 }),
    fadeOutStagger: zSlider({ min: 0, max: 8, step: 0.1 }),
  }),
  brand: z.object({
    show: z.boolean(),
    url: z.string(),
    color: zColor(),
    mark: zColor(),
    size: zSlider({ min: 16, max: 80 }),
    y: zSlider({ min: 0, max: 1920 }),
  }),
  motion: motionSchema,
});

