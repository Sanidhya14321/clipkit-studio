const unit = (max = 1, step = 0.01) => zSlider({ min: 0, max, step });

const frames = (max = 200) => zSlider({ min: 0, max });

const degrees = (limit = 45) => zSlider({ min: -limit, max: limit, step: 0.5 });

const offset = (limit = 500) => zSlider({ min: -limit, max: limit });

export const webServiceSchema = z.object({
  lines: zMultiline(),
  holdFrames: zSlider({ min: 24, max: 200 }),
  tilt: degrees(),
  turn: degrees(),
  lean: degrees(),
  swing: degrees(),
  spiderBody: zColor(),
  spiderMarks: zColor(),
  spiderStartX: offset(),
  spiderStartY: offset(),
  spiderEndX: offset(),
  spiderEndY: offset(),
  spiderTurn: degrees(180),
  sideWeb: z.boolean(),
  bokeh: z.boolean(),
  seed: zSlider({ min: 1, max: 99 }),
});

export type WebService = z.infer<typeof webServiceSchema>;

