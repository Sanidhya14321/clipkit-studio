import { z } from 'zod';
import { zColor, zMultiline, zSlider } from '../../control';
import {
  defaultMotion,
  kineticLook,
  lookSchema,
  motionSchema,
  promoMeta,
} from '../../promo-common';
import type { ClipMeta } from '../../registry';

const unit = (max = 1, step = 0.01) => zSlider({ min: 0, max, step });

const frames = (max = 120) => zSlider({ min: 0, max });

export const TEASER_BANDS = ['light', 'dark'] as const;

export const teaserWordSchema = z.object({
  text: z.string().max(24),
  band: z.enum(TEASER_BANDS),
  frames: zSlider({ min: 2, max: 90 }),
  glitchFrames: frames(90),
});

export type TeaserWord = z.infer<typeof teaserWordSchema>;

export const incomingCallTeaserSchema = z.object({
  call: z.object({
    caller: z.string().max(32),
    subtitle: z.string().max(40),
    sliderLabel: z.string().max(32),
    callerColor: zColor(),
    subtitleColor: zColor(),
    callerSize: zSlider({ min: 40, max: 160 }),
    subtitleSize: zSlider({ min: 16, max: 80 }),
    centerY: zSlider({ min: 400, max: 1500 }),
    pulseFrames: zSlider({ min: 6, max: 90, step: 0.5 }),
    pulseOffset: zSlider({ min: 0, max: 60, step: 0.25 }),
    pulseFloor: unit(),
    pillWidth: zSlider({ min: 240, max: 900 }),
    pillHeight: zSlider({ min: 60, max: 220 }),
    pillColor: zColor(),
    pillShade: zColor(),
    ringColor: zColor(),
    haloColor: zColor(),
    halo: unit(),
    labelColor: zColor(),
    shimmerColor: zColor(),
    shimmerFrames: zSlider({ min: 10, max: 120 }),
    knobColor: zColor(),
    answerColor: zColor(),
    declineColor: zColor(),
    declineDim: zColor(),
    hangupIcon: zColor(),
    slideStart: frames(400),
    slideFrames: zSlider({ min: 2, max: 60 }),
    declineFrames: zSlider({ min: 2, max: 60 }),
    holdFrames: frames(),
  }),
  words: z.object({
    list: z.array(teaserWordSchema).min(1).max(12),
    leadFrames: frames(),
    bandHeight: zSlider({ min: 200, max: 1920 }),
    bandOffsetY: zSlider({ min: -600, max: 600 }),
    lightBand: zColor(),
    lightInk: zColor(),
    darkBand: zColor(),
    darkInk: zColor(),
    glitchBand: zColor(),
    glitchInk: zColor(),
    glitchPattern: z.string().regex(/^[LD]*$/),
    letterFlicker: unit(),
    size: zSlider({ min: 40, max: 260 }),
    weight: zSlider({ min: 500, max: 800, step: 100 }),
    tracking: zSlider({ min: -0.1, max: 0.2, step: 0.005 }),
    textOffsetY: zSlider({ min: -200, max: 200 }),
    tilt: zSlider({ min: -12, max: 12, step: 0.5 }),
    distress: unit(),
  }),
  wall: z.object({
    title: zMultiline(),
    label: z.string().max(32),
    frames: zSlider({ min: 10, max: 300 }),
    panel: zColor(),
    panelLight: zColor(),
    cabinet: zColor(),
    shelf: zColor(),
    rail: zColor(),
    ink: zColor(),
    barFill: zColor(),
    slot: zColor(),
    titleSize: zSlider({ min: 60, max: 240 }),
    labelSize: zSlider({ min: 14, max: 60 }),
    progressFrom: unit(),
    progressTo: unit(),
    pullFrames: zSlider({ min: 4, max: 240 }),
    pullDistance: zSlider({ min: 0, max: 900 }),
    tilt: zSlider({ min: -400, max: 400 }),
    zoomFrom: zSlider({ min: 0.5, max: 1.5, step: 0.01 }),
    zoomTo: zSlider({ min: 0.5, max: 1.5, step: 0.01 }),
    light: unit(),
    vignette: unit(),
    softness: unit(4, 0.1),
    showHandle: z.boolean(),
  }),
  outro: z.object({
    text: z.string().max(40),
    color: zColor(),
    size: zSlider({ min: 40, max: 260 }),
    centerY: zSlider({ min: 300, max: 1600 }),
    tilt: zSlider({ min: -12, max: 12, step: 0.5 }),
    gapFrames: frames(),
    burn: z.boolean(),
    burnStart: frames(),
    burnColor: zColor(),
    burnCore: zColor(),
    burnStrength: unit(),
    burnSeed: zSlider({ min: 1, max: 99 }),
    swash: z.boolean(),
    swashColor: zColor(),
    swashStart: frames(),
    swashFrames: zSlider({ min: 2, max: 120 }),
  }),
  look: lookSchema,
  motion: motionSchema,
});

