import { z } from 'zod';
import { zColor, zSlider } from '../../control';
import {
  auraSchema,
  PICKER_FONTS,
  pickerLook,
  pickerMotion,
  steps,
  stepsSchema,
} from '../../picker-common';
import { FONT_WEIGHT, lookSchema, motionSchema, promoMeta } from '../../promo-common';
import type { ClipMeta } from '../../registry';

export const skillWheelSchema = z.object({
  title: z.string(),
  subtitle: z.string(),
  words: z.array(z.string()).min(1).max(24),
  heading: z.object({
    font: z.enum(PICKER_FONTS),
    size: zSlider({ min: 24, max: 220 }),
    weight: zSlider(FONT_WEIGHT),
    subtitleSize: zSlider({ min: 16, max: 140 }),
    subtitleWeight: zSlider(FONT_WEIGHT),
    gap: zSlider({ min: 0, max: 80 }),
    right: zSlider({ min: -200, max: 600 }),
  }),
  pointer: z.object({
    show: z.boolean(),
    color: zColor(),
    size: zSlider({ min: 10, max: 140 }),
    offset: zSlider({ min: -200, max: 600 }),
  }),
  wheel: z.object({
    font: z.enum(PICKER_FONTS),
    size: zSlider({ min: 16, max: 160 }),
    weight: zSlider(FONT_WEIGHT),
    activeScale: zSlider({ min: 0.5, max: 2, step: 0.01 }),
    radius: zSlider({ min: 100, max: 1000 }),
    spacing: zSlider({ min: 6, max: 60, step: 0.5 }),
    fadeStart: zSlider({ min: 0, max: 180 }),
    range: zSlider({ min: 20, max: 180 }),
    color: zColor(),
    activeColor: zColor(),
    direction: z.enum(['down', 'up']),
    entryTurn: zSlider({ min: 0, max: 6, step: 0.1 }),
  }),
  ticks: z.object({
    show: z.boolean(),
    color: zColor(),
    radius: zSlider({ min: 200, max: 1600 }),
    length: zSlider({ min: 4, max: 120 }),
    spacing: zSlider({ min: 1, max: 20, step: 0.1 }),
    tilt: zSlider({ min: -60, max: 60, step: 0.5 }),
    stroke: zSlider({ min: 0.5, max: 8, step: 0.1 }),
    dot: zSlider({ min: 0, max: 12, step: 0.1 }),
    speed: zSlider({ min: 0, max: 1.5, step: 0.01 }),
    idle: zSlider({ min: -0.5, max: 0.5, step: 0.005 }),
  }),
  center: z.object({
    x: zSlider({ min: -400, max: 1920 }),
    y: zSlider({ min: 0, max: 1080 }),
  }),
  entryFrames: zSlider({ min: 6, max: 60 }),
  steps: stepsSchema,
  aura: auraSchema,
  look: lookSchema,
  motion: motionSchema,
});

